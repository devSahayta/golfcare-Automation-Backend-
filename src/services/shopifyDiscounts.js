// src/services/shopifyDiscounts.js
//
// Member Pricing Engine Phase 4. Two kinds of discount code, both via
// REST Price Rules + Discount Codes (same auth/client pattern as
// shopifyWebhookRegistration.js — client_credentials token from
// shopifyAuth.js, axios, API version 2024-10). Deliberately NOT using
// Shopify customer IDs anywhere — neither code type needs one:
//
//   1. Standing member code — created once at enrollment. Percentage
//      off, store-wide, unlimited uses, no customer restriction. The
//      code string IS the customer's existing memberCode (GCXXXXXX) —
//      one concept, not two. Covers a member buying directly on the
//      website with no agent involved that session.
//
//   2. Fresh cart discount code — created fresh every time
//      create_checkout_link actually builds a real checkout for a
//      member. Fixed ₹ amount off the whole cart (computed variant-wise,
//      applied cart-wise — see resolveCheckoutPricing in
//      salesAgentTools.js), single use, short expiry. Covers both the
//      flat member price and a negotiated offer with the same
//      mechanism — there's never more than one discount code per
//      checkout, so there's no code-stacking question.

const axios = require("axios");
const { env } = require("../config/env");
const { getValidAccessToken } = require("./shopifyAuth");

const SHOPIFY_API_VERSION = "2024-10";

async function shopifyClient() {
  const { shopDomain } = env.shopify;
  const accessToken = await getValidAccessToken();
  return axios.create({
    baseURL: `https://${shopDomain}/admin/api/${SHOPIFY_API_VERSION}`,
    headers: {
      "X-Shopify-Access-Token": accessToken,
      "Content-Type": "application/json",
    },
    timeout: 15000,
  });
}

// Shopify's discount VALUE field is always a negative number string for
// both percentage and fixed_amount price rules — "-10.0" means 10% off,
// "-500.0" means ₹500 off. Easy to get backwards; centralized here so
// both functions below do it the same way.
function asNegativeValueString(amount) {
  return `-${Math.abs(Number(amount)).toFixed(1)}`;
}

// ============================================================================
// 1. Standing member discount code — created once at enrollment.
// ============================================================================
//
// Idempotent in effect, not just in name: if a Price Rule with this exact
// title already exists (e.g. enroll_membership's own idempotency guard
// called this twice for the same customer), Shopify will happily create a
// second one with a different id — REST price_rules has no unique
// constraint on title. Callers (enroll_membership) are responsible for
// only calling this once per customer; this function itself does not
// re-check.
async function createStandingMemberDiscountCode({ memberCode, percentOff }) {
  if (!memberCode) throw new Error("memberCode is required");
  const client = await shopifyClient();

  const priceRuleRes = await client.post("/price_rules.json", {
    price_rule: {
      title: `Member — ${memberCode}`,
      target_type: "line_item",
      target_selection: "all",
      allocation_method: "across",
      value_type: "percentage",
      value: asNegativeValueString(percentOff),
      customer_selection: "all",
      usage_limit: null,
      starts_at: new Date().toISOString(),
    },
  });
  const priceRuleId = priceRuleRes.data.price_rule.id;

  await client.post(`/price_rules/${priceRuleId}/discount_codes.json`, {
    discount_code: { code: memberCode },
  });

  return { priceRuleId, code: memberCode };
}

// ============================================================================
// 2. Fresh single-use cart discount code — created per real checkout.
// ============================================================================
//
// `code` is generated by the caller (salesAgentTools.js) — short-lived,
// unique per checkout, human-readable enough to show up clearly in
// Shopify's order/discount records for debugging later.
async function createCartDiscountCode({ code, amountOff, expiresAt }) {
  if (!code) throw new Error("code is required");
  if (!(Number(amountOff) > 0)) throw new Error("amountOff must be > 0");
  const client = await shopifyClient();

  const priceRuleRes = await client.post("/price_rules.json", {
    price_rule: {
      title: `Checkout — ${code}`,
      target_type: "line_item",
      target_selection: "all",
      allocation_method: "across",
      value_type: "fixed_amount",
      value: asNegativeValueString(amountOff),
      customer_selection: "all",
      usage_limit: 1,
      starts_at: new Date().toISOString(),
      ends_at: expiresAt ? new Date(expiresAt).toISOString() : undefined,
    },
  });
  const priceRuleId = priceRuleRes.data.price_rule.id;

  await client.post(`/price_rules/${priceRuleId}/discount_codes.json`, {
    discount_code: { code },
  });

  return { priceRuleId, code };
}

module.exports = { createStandingMemberDiscountCode, createCartDiscountCode };
